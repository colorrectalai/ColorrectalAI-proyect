BEGIN;

-- 1. Catálogos y entidades base
CREATE TABLE IF NOT EXISTS investigador (
    id_investigador SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(120) NOT NULL,
    correo VARCHAR(120),
    rol_equipo VARCHAR(60) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_investigador_correo UNIQUE (correo)
);

CREATE TABLE IF NOT EXISTS dataset (
    id_dataset SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    version VARCHAR(20) NOT NULL,
    fuente VARCHAR(80) NOT NULL,
    licencia VARCHAR(40) NOT NULL,
    doi VARCHAR(120),
    CONSTRAINT uq_dataset_nombre_version UNIQUE (nombre, version)
);

CREATE TABLE IF NOT EXISTS centro_origen (
    id_centro SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_dataset SMALLINT NOT NULL REFERENCES dataset(id_dataset),
    codigo_centro VARCHAR(20) NOT NULL,
    descripcion VARCHAR(120),
    CONSTRAINT uq_centro_dataset_codigo UNIQUE (id_dataset, codigo_centro)
);

CREATE TABLE IF NOT EXISTS paciente_anonimo (
    id_paciente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_centro SMALLINT NOT NULL REFERENCES centro_origen(id_centro),
    codigo_seudonimo VARCHAR(40) NOT NULL,
    CONSTRAINT uq_paciente_centro_codigo UNIQUE (id_centro, codigo_seudonimo)
);

CREATE TABLE IF NOT EXISTS clase_deteccion (
    id_clase SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(40) NOT NULL UNIQUE,
    descripcion VARCHAR(160)
);

-- 2. Dataset y anotaciones de referencia
CREATE TABLE IF NOT EXISTS imagen_dataset (
    id_imagen INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente INTEGER NOT NULL REFERENCES paciente_anonimo(id_paciente),
    nombre_archivo VARCHAR(160) NOT NULL,
    ruta_relativa VARCHAR(255) NOT NULL,
    formato VARCHAR(10) NOT NULL,
    ancho_px INTEGER NOT NULL CHECK (ancho_px > 0 AND ancho_px <= 65535),
    alto_px INTEGER NOT NULL CHECK (alto_px > 0 AND alto_px <= 65535),
    sha256 CHAR(64) NOT NULL UNIQUE,
    estado_calidad VARCHAR(12) NOT NULL DEFAULT 'pendiente'
        CHECK (estado_calidad IN ('pendiente','aprobada','descartada')),
    motivo_descarte VARCHAR(160),
    CONSTRAINT uq_imagen_paciente_archivo UNIQUE (id_paciente, nombre_archivo),
    CONSTRAINT ck_imagen_descarte CHECK (
        estado_calidad <> 'descartada'
        OR (motivo_descarte IS NOT NULL AND btrim(motivo_descarte) <> '')
    ),
    CONSTRAINT ck_imagen_formato CHECK (lower(formato) IN ('jpg','jpeg','png'))
);

CREATE TABLE IF NOT EXISTS anotacion_roi (
    id_anotacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_imagen INTEGER NOT NULL REFERENCES imagen_dataset(id_imagen) ON DELETE CASCADE,
    id_clase SMALLINT NOT NULL REFERENCES clase_deteccion(id_clase),
    bbox_x_centro NUMERIC(7,6) NOT NULL CHECK (bbox_x_centro BETWEEN 0 AND 1),
    bbox_y_centro NUMERIC(7,6) NOT NULL CHECK (bbox_y_centro BETWEEN 0 AND 1),
    bbox_ancho NUMERIC(7,6) NOT NULL CHECK (bbox_ancho > 0 AND bbox_ancho <= 1),
    bbox_alto NUMERIC(7,6) NOT NULL CHECK (bbox_alto > 0 AND bbox_alto <= 1),
    ruta_mascara VARCHAR(255)
);

-- 3. Particiones reproducibles por paciente
CREATE TABLE IF NOT EXISTS particion_dataset (
    id_particion SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_dataset SMALLINT NOT NULL REFERENCES dataset(id_dataset),
    nombre VARCHAR(60) NOT NULL,
    criterio VARCHAR(20) NOT NULL DEFAULT 'por_paciente'
        CHECK (criterio = 'por_paciente'),
    semilla INTEGER NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_particion_dataset_nombre UNIQUE (id_dataset, nombre)
);

CREATE TABLE IF NOT EXISTS asignacion_particion (
    id_particion SMALLINT NOT NULL REFERENCES particion_dataset(id_particion) ON DELETE CASCADE,
    id_paciente INTEGER NOT NULL REFERENCES paciente_anonimo(id_paciente) ON DELETE CASCADE,
    subconjunto VARCHAR(15) NOT NULL
        CHECK (subconjunto IN ('entrenamiento','validacion','prueba')),
    PRIMARY KEY (id_particion, id_paciente)
);

-- 4. Experimentos, modelos y evaluación
CREATE TABLE IF NOT EXISTS experimento (
    id_experimento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_investigador SMALLINT NOT NULL REFERENCES investigador(id_investigador),
    id_particion SMALLINT NOT NULL REFERENCES particion_dataset(id_particion),
    nombre VARCHAR(80) NOT NULL,
    entorno VARCHAR(60) NOT NULL,
    framework VARCHAR(60) NOT NULL,
    hiperparametros JSONB,
    semilla INTEGER,
    commit_git CHAR(40),
    fecha_inicio TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP,
    estado VARCHAR(12) NOT NULL
        CHECK (estado IN ('en_curso','finalizado','fallido')),
    CONSTRAINT ck_experimento_fechas CHECK (
        fecha_fin IS NULL OR fecha_fin >= fecha_inicio
    )
);

CREATE INDEX IF NOT EXISTS ix_experimento_estado_fecha
    ON experimento (estado, fecha_inicio);

CREATE TABLE IF NOT EXISTS version_modelo (
    id_modelo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_experimento INTEGER NOT NULL REFERENCES experimento(id_experimento),
    nombre VARCHAR(60) NOT NULL,
    version VARCHAR(20) NOT NULL,
    formato VARCHAR(5) NOT NULL CHECK (formato IN ('onnx','pt')),
    sha256_pesos CHAR(64) NOT NULL UNIQUE,
    url_release VARCHAR(255) NOT NULL,
    tamano_mb NUMERIC(7,2) CHECK (tamano_mb IS NULL OR tamano_mb > 0),
    fecha_publicacion TIMESTAMP NOT NULL,
    estado VARCHAR(10) NOT NULL
        CHECK (estado IN ('candidato','activo','retirado')),
    CONSTRAINT uq_modelo_nombre_version UNIQUE (nombre, version)
);

-- Índice parcial PostgreSQL: como máximo un modelo activo.
CREATE UNIQUE INDEX IF NOT EXISTS uq_modelo_un_activo
    ON version_modelo ((estado))
    WHERE estado = 'activo';

CREATE TABLE IF NOT EXISTS metrica (
    id_metrica SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE,
    descripcion VARCHAR(160)
);

CREATE TABLE IF NOT EXISTS evaluacion (
    id_evaluacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modelo INTEGER NOT NULL REFERENCES version_modelo(id_modelo),
    subconjunto VARCHAR(10) NOT NULL CHECK (subconjunto IN ('validacion','prueba')),
    umbral_confianza NUMERIC(4,3) NOT NULL
        CHECK (umbral_confianza BETWEEN 0 AND 1),
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_evaluacion UNIQUE (id_modelo, subconjunto, umbral_confianza)
);

CREATE TABLE IF NOT EXISTS evaluacion_metrica (
    id_evaluacion INTEGER NOT NULL REFERENCES evaluacion(id_evaluacion) ON DELETE CASCADE,
    id_metrica SMALLINT NOT NULL REFERENCES metrica(id_metrica),
    valor NUMERIC(8,6) NOT NULL,
    PRIMARY KEY (id_evaluacion, id_metrica)
);

-- 5. Registro opcional de operación de la API (no guarda imágenes)
CREATE TABLE IF NOT EXISTS catalogo_error (
    id_error SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_interno VARCHAR(40) NOT NULL UNIQUE,
    codigo_http SMALLINT NOT NULL CHECK (codigo_http BETWEEN 400 AND 599),
    mensaje_es VARCHAR(160) NOT NULL
);

CREATE TABLE IF NOT EXISTS solicitud_inferencia (
    id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_modelo INTEGER REFERENCES version_modelo(id_modelo),
    id_error SMALLINT REFERENCES catalogo_error(id_error),
    formato_archivo VARCHAR(10),
    tamano_bytes BIGINT CHECK (tamano_bytes IS NULL OR tamano_bytes >= 0),
    ancho_px INTEGER CHECK (ancho_px IS NULL OR ancho_px > 0),
    alto_px INTEGER CHECK (alto_px IS NULL OR alto_px > 0),
    latencia_ms BIGINT NOT NULL CHECK (latencia_ms >= 0),
    num_roi SMALLINT NOT NULL DEFAULT 0 CHECK (num_roi >= 0),
    CONSTRAINT ck_solicitud_modelo_o_error CHECK (
        id_modelo IS NOT NULL OR id_error IS NOT NULL
    )
);

CREATE TABLE IF NOT EXISTS resultado_roi (
    id_resultado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL REFERENCES solicitud_inferencia(id_solicitud) ON DELETE CASCADE,
    id_clase SMALLINT NOT NULL REFERENCES clase_deteccion(id_clase),
    orden SMALLINT NOT NULL CHECK (orden >= 0),
    confianza NUMERIC(5,4) NOT NULL CHECK (confianza BETWEEN 0 AND 1),
    bbox_x_centro NUMERIC(7,6) NOT NULL CHECK (bbox_x_centro BETWEEN 0 AND 1),
    bbox_y_centro NUMERIC(7,6) NOT NULL CHECK (bbox_y_centro BETWEEN 0 AND 1),
    bbox_ancho NUMERIC(7,6) NOT NULL CHECK (bbox_ancho > 0 AND bbox_ancho <= 1),
    bbox_alto NUMERIC(7,6) NOT NULL CHECK (bbox_alto > 0 AND bbox_alto <= 1),
    CONSTRAINT uq_resultado_solicitud_orden UNIQUE (id_solicitud, orden)
);

-- 6. Índices de consulta
CREATE INDEX IF NOT EXISTS ix_asignacion_paciente ON asignacion_particion(id_paciente);
CREATE INDEX IF NOT EXISTS ix_solicitud_error_fecha ON solicitud_inferencia(id_error, fecha_hora);
CREATE INDEX IF NOT EXISTS ix_solicitud_fecha ON solicitud_inferencia(fecha_hora);
CREATE INDEX IF NOT EXISTS ix_solicitud_modelo_fecha ON solicitud_inferencia(id_modelo, fecha_hora);
CREATE INDEX IF NOT EXISTS ix_resultado_clase_confianza ON resultado_roi(id_clase, confianza);

-- 7. Vistas de consulta del diseño
CREATE OR REPLACE VIEW v_servicio_diario AS
SELECT
    fecha_hora::date AS fecha,
    COUNT(*) AS total_solicitudes,
    ROUND(AVG(latencia_ms)::numeric, 2) AS latencia_media_ms,
    MAX(latencia_ms) AS latencia_maxima_ms,
    SUM(num_roi) AS total_roi
FROM solicitud_inferencia
GROUP BY fecha_hora::date;

CREATE OR REPLACE VIEW v_errores_por_tipo AS
SELECT
    ce.id_error,
    ce.codigo_interno,
    ce.codigo_http,
    ce.mensaje_es,
    COUNT(si.id_solicitud) AS total_errores
FROM catalogo_error ce
LEFT JOIN solicitud_inferencia si ON si.id_error = ce.id_error
GROUP BY ce.id_error, ce.codigo_interno, ce.codigo_http, ce.mensaje_es;

CREATE OR REPLACE VIEW v_metricas_modelo AS
SELECT
    vm.id_modelo,
    vm.nombre,
    vm.version,
    e.subconjunto,
    e.umbral_confianza,
    e.fecha,
    m.nombre AS metrica,
    em.valor
FROM version_modelo vm
JOIN evaluacion e ON e.id_modelo = vm.id_modelo
JOIN evaluacion_metrica em ON em.id_evaluacion = e.id_evaluacion
JOIN metrica m ON m.id_metrica = em.id_metrica;

CREATE OR REPLACE VIEW v_imagenes_por_subconjunto AS
SELECT
    pd.id_particion,
    pd.nombre AS particion,
    ap.subconjunto,
    COUNT(DISTINCT ap.id_paciente) AS total_pacientes,
    COUNT(i.id_imagen) AS total_imagenes
FROM particion_dataset pd
JOIN asignacion_particion ap ON ap.id_particion = pd.id_particion
LEFT JOIN imagen_dataset i ON i.id_paciente = ap.id_paciente
GROUP BY pd.id_particion, pd.nombre, ap.subconjunto;

